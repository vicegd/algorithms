/**
 * Introduction to algorithms, computational thinking, and fundamental data structures.
 *
 * <p>This package is the starting point for learners new to algorithm design.
 * It covers two complementary areas:</p>
 * <ul>
 *   <li><strong>Algorithm introduction</strong> — what an algorithm is, how to measure
 *       its correctness and efficiency, and how to improve naive solutions step by step.</li>
 *   <li><strong>Principles &amp; data structures</strong> — the foundational building blocks
 *       (recursion, search, core data structures) required before studying advanced topics.</li>
 * </ul>
 *
 * <h2>Algorithm Introduction</h2>
 * <ul>
 *   <li><strong>Correctness</strong> — does the algorithm always produce the right answer?</li>
 *   <li><strong>Efficiency</strong> — how does running time grow with input size (Big-O)?</li>
 *   <li><strong>Stress testing</strong> — comparing a naive solution against an optimised
 *       one on random inputs to detect bugs.</li>
 * </ul>
 *
 * <h2>Principles &amp; Fundamentals</h2>
 * <ul>
 *   <li><strong>Recursion</strong> — base cases, inductive reasoning, call-stack mechanics.</li>
 *   <li><strong>Search algorithms</strong> — sequential search, sentinel search, binary search.</li>
 *   <li><strong>Core data structures</strong> — arrays, linked lists, stacks, queues,
 *       sets, priority queues (see {@link topics.introduction.examples}).</li>
 * </ul>
 *
 * <h2>Classes in This Package</h2>
 * <ul>
 *   <li>{@link topics.introduction.HelloWorld} — minimal sanity-check program</li>
 *   <li>{@link topics.introduction.MaxPairWiseProduct} — O(n²) naive max-product</li>
 *   <li>{@link topics.introduction.MaxPairWiseProduct2} — first optimised variant</li>
 *   <li>{@link topics.introduction.MaxPairWiseProduct3} — second optimised variant</li>
 *   <li>{@link topics.introduction.MaxPairWiseProduct4} — third optimised variant</li>
 *   <li>{@link topics.introduction.MaxPairWiseProduct5} — fourth optimised variant</li>
 *   <li>{@link topics.introduction.MaxPairWiseProduct6} — O(n) optimal solution</li>
 *   <li>{@link topics.introduction.MaxPairWiseProductRandomNumbers} — stress-test harness</li>
 *   <li>{@link topics.introduction.Factorial} — iterative and recursive factorial</li>
 *   <li>{@link topics.introduction.GetAdditionFromList} — sum of a list of numbers</li>
 *   <li>{@link topics.introduction.GetMaximumFromList} — maximum of a list of numbers</li>
 *   <li>{@link topics.introduction.Search} — sequential and binary search demonstrations</li>
 * </ul>
 */
